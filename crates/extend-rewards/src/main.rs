async fn send_proposals(
    worker: &Worker<Mainnet>,
    common: &CommonArgs,
    proposals: &[(String, ProposalInput)],
) -> Result<()> {
    let key = env::var("PRIVATE_KEY")
        .context("PRIVATE_KEY is missing; add it to .env or the environment")?;
    let secret_key: SecretKey = key.parse().context("PRIVATE_KEY is invalid")?;
    let bond =
        NearToken::from_yoctonear(parse_units(&common.bond, 24).context("invalid proposal bond")?);

    for (label, proposal) in proposals {
        let id = chain::add_proposal(
            worker,
            common.signer.clone(),
            secret_key.clone(),
            &common.dao,
            proposal,
            bond,
        )
        .await?;
        println!(
            "\n{label} proposal #{id} created: https://trezu.app/{}/requests/{id}",
            common.dao
        );
    }
    Ok(())
}

fn format_timestamp_ns(ns: u64) -> String {
    let seconds = ns / 1_000_000_000;
    let nanos = (ns % 1_000_000_000) as u32;
    i64::try_from(seconds)
        .ok()
        .and_then(|seconds| DateTime::<Utc>::from_timestamp(seconds, nanos))
        .map(|datetime| datetime.format("%Y-%m-%d %H:%M:%S UTC").to_string())
        .unwrap_or_else(|| ns.to_string())
}

/// Compact, grouped display amount (not suitable for re-parsing).
fn format_amount(value: u128, decimals: u8) -> String {
    format_f64_amount(units_to_f64(value, decimals))
}

fn format_f64_amount(value: f64) -> String {
    if !value.is_finite() {
        return value.to_string();
    }
    if value == 0.0 {
        return "0".to_string();
    }
    let abs = value.abs();
    if abs < 0.000001 {
        return format!("{value:.4e}");
    }
    let precision = if abs >= 1.0 {
        2
    } else if abs >= 0.01 {
        4
    } else {
        6
    };
    add_commas(&trim_trailing_zeros(format!(
        "{value:.precision$}",
        precision = precision
    )))
}

fn trim_trailing_zeros(mut value: String) -> String {
    if value.contains('.') {
        while value.ends_with('0') {
            value.pop();
        }
        if value.ends_with('.') {
            value.pop();
        }
    }
    value
}

fn add_commas(value: &str) -> String {
    let (sign, value) = match value.strip_prefix('-') {
        Some(value) => ("-", value),
        None => ("", value),
    };
    let (integer, fraction) = match value.split_once('.') {
        Some((integer, fraction)) => (integer, Some(fraction)),
        None => (value, None),
    };
    let mut grouped = String::new();
    for (index, character) in integer.chars().rev().enumerate() {
        if index > 0 && index % 3 == 0 {
            grouped.push(',');
        }
        grouped.push(character);
    }
    let grouped: String = grouped.chars().rev().collect();
    match fraction {
        Some(fraction) => format!("{sign}{grouped}.{fraction}"),
        None => format!("{sign}{grouped}"),
    }
}

/// Exact human amount used in generated commands.
fn format_units(value: u128, decimals: u8) -> String {
    if decimals == 0 {
        return value.to_string();
    }
    let Some(factor) = 10u128.checked_pow(decimals as u32) else {
        return value.to_string();
    };
    let whole = value / factor;
    let fractional = value % factor;
    if fractional == 0 {
        return whole.to_string();
    }
    let mut formatted = format!("{whole}.{fractional:0width$}", width = decimals as usize);
    while formatted.ends_with('0') {
        formatted.pop();
    }
    formatted
}

#[cfg(test)]
mod tests {
    use super::*;
    use near_sdk::json_types::{U128, U64};

    fn farm(amount: u128, start: u64, end: u64, active: bool) -> chain::Farm {
        chain::Farm {
            farm_id: 0,
            name: "Dogshit".to_string(),
            token_id: "shit.0xshitzu.near".parse().unwrap(),
            amount: U128(amount),
            start_date: U64(start),
            end_date: U64(end),
            active,
        }
    }

    #[test]
    fn remaining_farm_shares_is_linear() {
        let farm = farm(1_000_000_000_000_000_000_000_000_000, 1_000, 2_000, true);
        assert!((remaining_farm_shares(&farm, 1_500, 24) - 500.0).abs() < 1e-9);
        assert!((remaining_farm_shares(&farm, 500, 24) - 1_000.0).abs() < 1e-9);
        assert_eq!(remaining_farm_shares(&farm, 2_000, 24), 0.0);
    }

    #[test]
    fn inactive_farm_has_no_remaining_rewards() {
        let farm = farm(1_000_000_000_000_000_000_000_000_000, 1_000, 2_000, false);
        assert_eq!(remaining_farm_shares(&farm, 1_500, 24), 0.0);
    }

    #[test]
    fn formats_units() {
        assert_eq!(format_units(300_000_000_000_000_000_000_000, 18), "300000");
        assert_eq!(format_units(1_500_000_000_000_000_000_000_000, 24), "1.5");
        assert_eq!(format_units(0, 24), "0");
    }

    #[test]
    fn formats_display_amounts_with_grouping() {
        assert_eq!(
            format_amount(300_000_000_000_000_000_000_000, 18),
            "300,000"
        );
        assert_eq!(
            format_amount(16_091_681_890_521_040_032_694_747, 18),
            "16,091,681.89"
        );
        assert_eq!(format_amount(544_824_836_614_138_053, 18), "0.5448");
        assert_eq!(format_amount(8_767_150_686_365_520_664_281_505, 24), "8.77");
        assert_eq!(format_f64_amount(1_006_167.214946), "1,006,167.21");
        assert_eq!(format_f64_amount(0.0), "0");
    }

    #[test]
    fn formats_usd_with_grouping() {
        assert_eq!(format_usd(1_079.37), "$1,079.37");
        assert_eq!(format_usd(0.001234), "$0.0012");
        assert_eq!(format_usd(0.000012), "$1.20e-5");
        assert_eq!(format_price(0.001437), "$0.001437");
        assert_eq!(format_price(6.484e-9), "$6.4840e-9");
    }
}
