#[derive(Subcommand)]
enum Command {
    /// Propose sending one or more FTs from the DAO to the Dogshit contract
    SendTokens(SendTokensArgs),
    /// Propose minting DOGSHIT shares from all pending deposits
    MintShares(MintSharesArgs),
    /// Propose transferring DOGSHIT shares to the pool and updating the farm
    ExtendFarm(ExtendFarmArgs),
    /// Propose removing one or more reward tokens from the Dogshit contract
    RemoveRewards(RemoveRewardsArgs),
    /// Preview the APR/APY generated by a set of deposits and farm shares
    Preview(PreviewArgs),
    /// Show pending deposits, DAO DOGSHIT balance, and the current farm
    Status,
}

